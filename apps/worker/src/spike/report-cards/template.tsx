function Traits({
  title,
  rows,
}: {
  title: string
  rows: [string, number][]
}): JSX.Element {
  return (
    <table className="traits">
      <thead>
        <tr>
          <th className="s">{title}</th>
          <th>1–5</th>
        </tr>
      </thead>
      <tbody>
        {rows.map(([name, rating]) => (
          <tr key={name}>
            <td className="s">{name}</td>
            <td className="n">{rating}</td>
          </tr>
        ))}
      </tbody>
    </table>
  )
}

